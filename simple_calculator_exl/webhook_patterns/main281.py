async def comment_pr(owner: str, repo: str, pr: int, comment: PRComment, token: str, client: httpx.AsyncClient):
    """
    Dispatches a standardized global markdown message block to the PR main text board.
    """
    await client.post(
        f"https://api.github.com/repos/{owner}/{repo}/issues/{pr}/comments",
        headers={"Authorization": f"Bearer {token}"},
        json=comment.to_github_payload()
    )

# -----------------------------
# ✅ Review (Approve / Reject + Batched Inline Comments)
# -----------------------------
async def review_pr(
    owner: str, 
    repo: str, 
    pr: int, 
    token: str, 
    client: httpx.AsyncClient, 
    event: str, 
    message: str,
    comments: Optional[List[dict]] = None
):
    """
    Submits a structured Pull Request review configuration to GitHub.

    Can simultaneously attach multi-file inline code level feedback annotations 
    in a unified batch payload event.

    Args:
        owner (str): Repository owner.
        repo (str): Repository name.
        pr (int): Target Pull Request numeric identifier.
        token (str): Scoped App installation token.
        client (httpx.AsyncClient): The active HTTP workspace client instance.
        event (str): Core event type string ("APPROVE", "REQUEST_CHANGES", "COMMENT").
        message (str): Global body summary statement text attached to the review state.
        comments (Optional[List[dict]]): List of specific multi-line layout dictionaries 
            targeting file coordinates.

    Raises:
        HTTPException: 500 if the GitHub server returns an invalid status response.
    """
    payload = {
        "event": event,
        "body": message
    }

    if comments:
        payload["comments"] = comments

    url = f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr}/reviews"

    res = await client.post(
        url,
        headers={"Authorization": f"Bearer {token}"},
        json=payload
    )

    if res.status_code not in [200, 201]:
        logger.error(f"Failed to submit PR review: {res.text}")
        raise HTTPException(500, "Failed to submit PR review")
    
    logger.info("Successfully submitted batched PR review and inline comments.")


def should_auto_approve(files: list) -> bool:
    """
    Heuristic rule checkpoint engine determining automated code approval eligibility.

    Args:
        files (list): Aggregated evaluation list containing tracked document configurations.

    Returns:
        bool: True if the file change footprint size falls below the safety buffer limit.
    """
    return len(files) <= 20

