# 📥 PR Data
# -----------------------------
async def fetch_pr_details_and_files(owner: str, repo: str, pr: int, token: str, client: httpx.AsyncClient) -> tuple:
    """
    Fetches high-level metadata combined with comprehensive paginated file structural arrays.

    Args:
        owner (str): Repository owner.
        repo (str): Repository name.
        pr (int): Target Pull Request numeric identifier.
        token (str): Scoped App installation token.
        client (httpx.AsyncClient): The active HTTP workspace client instance.

    Returns:
        tuple: A pair containing (files_list: List[dict], pr_data: dict).
    """
    pr_res = await client.get(
        f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr}",
        headers={"Authorization": f"Bearer {token}"}
    )
    pr_data = pr_res.json()

    files, page = [], 1
    while True:
        res = await client.get(
            f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr}/files",
            headers={"Authorization": f"Bearer {token}"},
            params={"page": page, "per_page": 100}
        )
        data = res.json()
        if not data:
            break
        files.extend(data)
        page += 1

    return files, pr_data

