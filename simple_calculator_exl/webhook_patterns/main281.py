# 📄 Fetch File
# -----------------------------
@retry(
    stop=stop_after_attempt(4),
    wait=wait_exponential(multiplier=0.5, min=1, max=10),
    retry=retry_if_exception_type((httpx.RequestError,)),
    reraise=True,
)
async def fetch_file_content(owner: str, repo: str, path: str, ref: str, token: str, client: httpx.AsyncClient) -> Optional[str]:
    """
    Retrieves the raw string contents of an explicit file reference from GitHub.

    Wrapped with exponential backoff handling to tolerate intermittent request errors.

    Args:
        owner (str): Repository namespace organization or user owner.
        repo (str): Repository target name identifier.
        path (str): Relative destination path to the file.
        ref (str): Target Git SHA commit hash, branch reference, or tag name.
        token (str): Scoped App installation authentication bearer token.
        client (httpx.AsyncClient): The active HTTP workspace client instance.

    Returns:
        Optional[str]: Raw plain-text file contents if successful, else None.
    """
    if not path or not ref:
        return None

    res = await client.get(
        f"https://api.github.com/repos/{owner}/{repo}/contents/{path}?ref={ref}",
        headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github.v3.raw"}
    )
    return res.text if res.status_code == 200 else None

