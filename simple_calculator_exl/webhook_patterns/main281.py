# 🔑 JWT
# -----------------------------
def generate_jwt() -> str:
    """
    Generates a localized JSON Web Token signed with the App's private RSA key.
    
    Tokens are signed using the RS256 algorithm and hold a 10-minute expiration
    window, matching GitHub App authentication expectations.

    Returns:
        str: Encoded JWT string.
    """
    now = int(time.time()) - 30
    payload = {"iat": now, "exp": now + 600, "iss": APP_ID}
    token = jwt.encode(payload, PRIVATE_KEY, algorithm="RS256")
    return token.decode() if isinstance(token, bytes) else token

