@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    Manages the startup and shutdown lifecycles of the FastAPI application.
    
    Initializes a persistent, high-performance httpx.AsyncClient configuration
    attached to the application state for pooled HTTP connection recycling,
    and ensures resources are gracefully cleaned up on exit.
    """
    timeout = httpx.Timeout(timeout=10.0, connect=10.0, read=45.0, write=10.0, pool=10.0)
    limits = httpx.Limits(max_connections=50, max_keepalive_connections=20)

    app.state.client = httpx.AsyncClient(
        timeout=timeout,
        limits=limits,
        headers={"Accept": "application/vnd.github+json"}
    )

    logger.info("HTTP client initialized")
    yield

    await app.state.client.aclose()
    logger.info("HTTP client closed")

app = FastAPI(title="GitHub PR Bot", lifespan=lifespan)

