class FileStats(BaseModel):
    """
    Pydantic schema to track categorizations of files targeted by a Pull Request.
    """
    added: List[str] = []
    modified: List[str] = []
    removed: List[str] = []


class PRComment(BaseModel):
    """
    Data model responsible for structuring and formatting markdown notification summaries 
    published directly to GitHub Pull Request issue comment threads.
    """
    title: Optional[str] = None
    summary: Optional[str] = None
    pr_number: Optional[int] = None
    repository: Optional[str] = None
    total_files: Optional[int] = None
    file_stats: Optional[FileStats] = None
    notes: Optional[str] = None

    def build_body(self) -> str:
        """
        Compiles the defined attributes into a cleanly formatted markdown string.

        Returns:
            str: The fully formatted markdown body intended for GitHub.
        """
        lines = []

        if self.title:
            lines.append(f"## {self.title}")

        if self.summary:
            lines.append(self.summary)

        if self.pr_number and self.repository:
            lines.append(f"\n📦 **Repo:** `{self.repository}`")
            lines.append(f"🔢 **PR:** #{self.pr_number}")

        if self.total_files is not None:
            lines.append(f"📁 **Files changed:** {self.total_files}")

        if self.file_stats:
            if self.file_stats.added:
                lines.append("\n### ➕ Added Files")
                lines.extend([f"- `{f}`" for f in self.file_stats.added])

            if self.file_stats.modified:
                lines.append("\n### ✏️ Modified Files")
                lines.extend([f"- `{f}`" for f in self.file_stats.modified])

            if self.file_stats.removed:
                lines.append("\n### ❌ Removed Files")
                lines.extend([f"- `{f}`" for f in self.file_stats.removed])

        if self.notes:
            lines.append(f"\n💡 {self.notes}")

        lines.append("\n---\n🤖 Generated by PR Bot")

        return "\n".join(lines)

    def to_github_payload(self) -> dict:
        """
        Wraps the generated markdown block into a JSON-serializable dictionary object.

        Returns:
            dict: GitHub API-compliant text payload containing the comment body.
        """
        return {"body": self.build_body()}

# -----------------------------
# 🔐 Verify Signature
# -----------------------------
def verify_signature(payload_body: bytes, signature: str):
    """
    Validates that incoming webhook requests originate from authentic GitHub payloads.

    Uses HMAC hex digests and constant-time comparisons to evaluate signatures
    against the configured `GITHUB_WEBHOOK_SECRET` environment variable.

    Args:
        payload_body (bytes): The raw request body bytes.
        signature (str): The 'X-Hub-Signature-256' header value passed by GitHub.

    Raises:
        HTTPException: 400 if the signature is missing; 403 if computation validation fails.
    """
    if not signature:
        raise HTTPException(400, "Missing signature")

    sha_name, sig = signature.split("=")

    mac = hmac.new(
        GITHUB_SECRET.encode(),
        msg=payload_body,
        digestmod=hashlib.sha256,
    )

    if not hmac.compare_digest(mac.hexdigest(), sig):
        raise HTTPException(403, "Invalid signature")

