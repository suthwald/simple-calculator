@app.post("/webhook/github")
async def webhook(
    request: Request,
    background_tasks: BackgroundTasks,
    x_hub_signature_256: str = Header(None),
    x_github_event: str = Header(None),
):
    """
    Listens for and intercepts active GitHub real-time event webhook payloads.

    Validates cryptographic headers, processes incoming Pull Request actions,
    and assigns confirmed analysis tasks to the FastAPI background worker queue.

    Args:
        request (Request): Core FastAPI context wrapper holding incoming payload data.
        background_tasks (BackgroundTasks): Native non-blocking service scheduler context.
        x_hub_signature_256 (str): Cryptographic security verification string header.
        x_github_event (str): Categorized classification event type string header.

    Returns:
        dict: Short string dict map indicating processing or ignore status.
    """
    body = await request.body()
    verify_signature(body, x_hub_signature_256)

    payload = json.loads(body)

    if x_github_event != "pull_request":
        return {"msg": "ignored"}

    if payload.get("action") not in ["opened", "synchronize", "reopened"]:
        return {"msg": "ignored"}

    installation = payload.get("installation")
    if not installation:
        return {"msg": "no installation"}

    background_tasks.add_task(
        process_pr,
        payload["repository"]["owner"]["login"],
        payload["repository"]["name"],
        payload["pull_request"]["number"],
        installation["id"]
    )

    return {"status": "processing"}

