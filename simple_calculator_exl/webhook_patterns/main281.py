# 🎟️ Token
# -----------------------------
async def get_installation_token(installation_id: int, client: httpx.AsyncClient) -> str:
    """
    Requests a short-lived scoped installation access token for authorization.

    Exchanges the global App JWT for an installation-specific token to interact
    with individual repository API paths.

    Args:
        installation_id (int): Target GitHub App installation identifier.
        client (httpx.AsyncClient): The active HTTP workspace client instance.

    Returns:
        str: Temporary authentication bearer token string.
    """
    res = await client.post(
        f"https://api.github.com/app/installations/{installation_id}/access_tokens",
        headers={"Authorization": f"Bearer {generate_jwt()}"}
    )
    if res.status_code != 201:
        raise HTTPException(500, "Token generation failed")
    return res.json()["token"]

