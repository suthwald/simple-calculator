def generate_jwt() -> str:
    """Generates a JSON Web Token (JWT) signed with the GitHub App private key.

    Uses an RS256 algorithm. Includes a 30-second clock skew buffer for creation time.

    Returns:
        str: Encoded JWT string authorized for GitHub App administrative requests.
    """
    now = int(time.time()) - 30
    payload = {"iat": now, "exp": now + 600, "iss": APP_ID}
    token = jwt.encode(payload, PRIVATE_KEY, algorithm="RS256")
    return token.decode() if isinstance(token, bytes) else token


async def get_installation_token_by_repo(owner: str, repo: str, client: httpx.AsyncClient) -> Optional[str]:
    """Retrieves an ephemeral installation access token for a repository target.

    Queries the GitHub API to find the specific installation ID mapping for the repository, 
    then exchanges the primary JWT for a scoped repository access token.

    Args:
        owner (str): Owner or organization name of the repository.
        repo (str): Name of the repository.
        client (httpx.AsyncClient): HTTPX async client to process network requests.

    Returns:
        Optional[str]: Short-lived installation access token if successful, else None.
    """
    jwt_token = generate_jwt()
    res = await client.get(
        f"https://api.github.com/repos/{owner}/{repo}/installation",
        headers={"Authorization": f"Bearer {jwt_token}"}
    )
    if res.status_code != 200:
        logger.error(f"Could not find App installation metadata for {owner}/{repo}.")
        return None
        
    installation_id = res.json()["id"]
    token_res = await client.post(
        f"https://api.github.com/app/installations/{installation_id}/access_tokens",
        headers={"Authorization": f"Bearer {jwt_token}"}
    )
    if token_res.status_code != 201:
        logger.error(f"Token generation failed for installation {installation_id}")
        return None
    return token_res.json()["token"]


