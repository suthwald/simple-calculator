class FileStats(BaseModel):
    """Data model tracking the classification of files modified within a Pull Request.

    Attributes:
        added (List[str]): List of file paths added in the PR.
        modified (List[str]): List of file paths modified in the PR.
        removed (List[str]): List of file paths removed in the PR.
    """
    added: List[str] = []
    modified: List[str] = []
    removed: List[str] = []


class PRComment(BaseModel):
    """Data model for constructing structured Markdown summaries for GitHub PR reviews.

    Attributes:
        title (Optional[str]): The main header title for the comment.
        summary (Optional[str]): A brief summary message of the analysis.
        pr_number (Optional[int]): Target Pull Request identity number.
        repository (Optional[str]): Full name of the repository (owner/repo).
        total_files (Optional[int]): Total count of altered files.
        file_stats (Optional[FileStats]): Segmented breakdown of file statuses.
        notes (Optional[str]): Additional automated system notes or dynamic insights.
    """
    title: Optional[str] = None
    summary: Optional[str] = None
    pr_number: Optional[int] = None
    repository: Optional[str] = None
    total_files: Optional[int] = None
    file_stats: Optional[FileStats] = None
    notes: Optional[str] = None

    def build_body(self) -> str:
        """Assembles model attributes into a clean, formatted Markdown string.

        Returns:
            str: Markdown-formatted text ready for a GitHub issue or PR comment.
        """
        lines = []
        if self.title: lines.append(f"## {self.title}")
        if self.summary: lines.append(self.summary)

        if self.pr_number and self.repository:
            lines.append(f"\n📦 **Repo:** `{self.repository}`")
            lines.append(f"🔢 **PR:** #{self.pr_number}")

        if self.total_files is not None:
            lines.append(f"📁 **Files changed:** {self.total_files}")

        if self.file_stats:
            if self.file_stats.added:
                lines.append("\n### ➕ Added Files")
                lines.extend([f"- `{f}`" for f in self.file_stats.added])
            if self.file_stats.modified:
                lines.append("\n### ✏️ Modified Files")
                lines.extend([f"- `{f}`" for f in self.file_stats.modified])
            if self.file_stats.removed:
                lines.append("\n### ❌ Removed Files")
                lines.extend([f"- `{f}`" for f in self.file_stats.removed])

        if self.notes: lines.append(f"\n💡 {self.notes}")
        lines.append("\n---\n🤖 Generated by PR Bot via Request Engine")
        return "\n".join(lines)

    def to_github_payload(self) -> Dict[str, str]:
        """Formats the comment body into a standard GitHub API request payload structure.

        Returns:
            Dict[str, str]: JSON payload dictionary containing the comment text.
        """
        return {"body": self.build_body()}


