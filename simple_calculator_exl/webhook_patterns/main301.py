@asynccontextmanager
async def lifespan(app: FastAPI):
    """Manages the operational lifecycle setup and breakdown for the FastAPI application.

    Configures and provisions a shared asynchronous HTTPX connection pool on application startup, 
    mounting it directly to `app.state.client`, and gracefully cleans up resources upon shutdown.
    """
    timeout = httpx.Timeout(timeout=10.0, connect=10.0, read=45.0, write=10.0, pool=10.0)
    limits = httpx.Limits(max_connections=50, max_keepalive_connections=20)

    async with httpx.AsyncClient(timeout=timeout, limits=limits, headers={"Accept": "application/vnd.github+json"}) as client:
        app.state.client = client
        logger.info("HTTP Client Session safely locked in.")
        yield
    logger.info("HTTP Client Session cleanly broken down.")


app = FastAPI(title="GitHub PR Bot Router Only", lifespan=lifespan)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# -----------------------------
# 🔥 Review Target Routing Endpoint
# -----------------------------
@app.post("/review-pr")
async def trigger_pr_review(
    owner: str = Query(..., description="GitHub repository owner"),
    repo: str = Query(..., description="GitHub repository name"),
    pr_number: int = Query(..., description="Target Pull Request ID number")
):
    """Triggers an instantaneous, one-shot metadata pull and review analysis for a specific PR.

    Validates installation access token permissions for the target repository context, 
    routes requirements to the evaluation analyzer pipeline, and returns execution metrics.
    """
    client = app.state.client
    
    token = await get_installation_token_by_repo(owner, repo, client)
    if not token:
        raise HTTPException(
            status_code=401, 
            detail=f"Could not authorize GitHub App permissions installation mapping for target metadata {owner}/{repo}"
        )
        
    try:
        result = await process_pr_pipeline(owner, repo, pr_number, token, client)
        return result
    except Exception as e:
        logger.error(f"Execution pipeline breakdown on PR #{pr_number}: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=str(e))
