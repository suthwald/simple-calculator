class FileStats(BaseModel):
    added: List[str] = []
    modified: List[str] = []
    removed: List[str] = []


class PRComment(BaseModel):
    title: Optional[str] = None
    summary: Optional[str] = None
    pr_number: Optional[int] = None
    repository: Optional[str] = None
    total_files: Optional[int] = None
    file_stats: Optional[FileStats] = None
    notes: Optional[str] = None

    def build_body(self) -> str:
        lines = []

        if self.title:
            lines.append(f"## {self.title}")

        if self.summary:
            lines.append(self.summary)

        if self.pr_number and self.repository:
            lines.append(f"\n📦 **Repo:** `{self.repository}`")
            lines.append(f"🔢 **PR:** #{self.pr_number}")

        if self.total_files is not None:
            lines.append(f"📁 **Files changed:** {self.total_files}")

        if self.file_stats:
            if self.file_stats.added:
                lines.append("\n### ➕ Added Files")
                lines.extend([f"- `{f}`" for f in self.file_stats.added])

            if self.file_stats.modified:
                lines.append("\n### ✏️ Modified Files")
                lines.extend([f"- `{f}`" for f in self.file_stats.modified])

            if self.file_stats.removed:
                lines.append("\n### ❌ Removed Files")
                lines.extend([f"- `{f}`" for f in self.file_stats.removed])

        if self.notes:
            lines.append(f"\n💡 {self.notes}")

        lines.append("\n---\n🤖 Generated by PR Bot")

        return "\n".join(lines)

    def to_github_payload(self):
        return {"body": self.build_body()}

