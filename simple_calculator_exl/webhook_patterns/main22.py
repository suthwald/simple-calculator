async def comment_pr(owner, repo, pr, comment: PRComment, token, client):
    await client.post(
        f"https://api.github.com/repos/{owner}/{repo}/issues/{pr}/comments",
        headers={"Authorization": f"Bearer {token}"},
        json=comment.to_github_payload()
    )

# -----------------------------
# ✅ Review (Approve / Reject)
# -----------------------------
async def review_pr(owner, repo, pr, token, client, event: str, message: str):
    await client.post(
        f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr}/reviews",
        headers={"Authorization": f"Bearer {token}"},
        json={"event": event, "body": message}
    )

def should_auto_approve(files):
    return len(files) <= 20

# -----------------------------
# 🚀 Process PR
# -----------------------------
async def process_pr(owner, repo, pr, installation_id):
    client = app.state.client

    try:
        token = await get_installation_token(installation_id, client)
        files, pr_data = await fetch_pr_details_and_files(owner, repo, pr, token, client)

        semaphore = asyncio.Semaphore(10)

        async def process_file(f):
            filename = f["filename"]
            status = f.get("status", "modified")

            async def fetch_safe(path, ref):
                async with semaphore:
                    return await fetch_file_content(owner, repo, path, ref, token, client)

            before = fetch_safe(f.get("previous_filename") or filename, pr_data["base"]["sha"]) \
                if status in ["modified", "removed", "renamed"] else asyncio.sleep(0, result=None)

            after = fetch_safe(filename, pr_data["head"]["sha"]) \
                if status in ["modified", "added", "renamed"] else asyncio.sleep(0, result=None)

            before_content, after_content = await asyncio.gather(before, after)

            return {"file": filename, "status": status}

        structured_files = await asyncio.gather(*(process_file(f) for f in files))

        # 🧠 Build comment
        comment = PRComment(
            title="✅ PR Processed Successfully",
            summary="All files analyzed and structured.",
            pr_number=pr,
            repository=f"{owner}/{repo}",
            total_files=len(structured_files),
            file_stats=FileStats(
                added=[f["file"] for f in structured_files if f["status"] == "added"],
                modified=[f["file"] for f in structured_files if f["status"] == "modified"],
                removed=[f["file"] for f in structured_files if f["status"] == "removed"],
            ),
            notes="Auto-approved because changes are small."
        )

        # ⚡ Run comment + review in parallel
        await asyncio.gather(
            comment_pr(owner, repo, pr, comment, token, client),
            review_pr(
                owner, repo, pr, token, client,
                "APPROVE" if should_auto_approve(structured_files) else "REQUEST_CHANGES",
                "✅ Auto-approved" if should_auto_approve(structured_files) else "⚠️ Too large PR"
            )
        )

    except Exception as e:
        logger.error(f"Error: {e}", exc_info=True)

