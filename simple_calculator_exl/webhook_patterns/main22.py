async def get_installation_token(installation_id: int, client: httpx.AsyncClient):
    res = await client.post(
        f"https://api.github.com/app/installations/{installation_id}/access_tokens",
        headers={"Authorization": f"Bearer {generate_jwt()}"}
    )
    if res.status_code != 201:
        raise HTTPException(500, "Token generation failed")
    return res.json()["token"]

# -----------------------------
# 📄 Fetch File
# -----------------------------
@retry(
    stop=stop_after_attempt(4),
    wait=wait_exponential(multiplier=0.5, min=1, max=10),
    retry=retry_if_exception_type((httpx.RequestError,)),
    reraise=True,
)
async def fetch_file_content(owner, repo, path, ref, token, client):
    if not path or not ref:
        return None

    res = await client.get(
        f"https://api.github.com/repos/{owner}/{repo}/contents/{path}?ref={ref}",
        headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github.v3.raw"}
    )
    return res.text if res.status_code == 200 else None

# -----------------------------
# 📥 PR Data
# -----------------------------
async def fetch_pr_details_and_files(owner, repo, pr, token, client):
    pr_res = await client.get(
        f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr}",
        headers={"Authorization": f"Bearer {token}"}
    )
    pr_data = pr_res.json()

    files, page = [], 1
    while True:
        res = await client.get(
            f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr}/files",
            headers={"Authorization": f"Bearer {token}"},
            params={"page": page, "per_page": 100}
        )
        data = res.json()
        if not data:
            break
        files.extend(data)
        page += 1

    return files, pr_data

