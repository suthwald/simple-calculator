def generate_jwt():
    now = int(time.time()) - 30
    payload = {"iat": now, "exp": now + 600, "iss": APP_ID}
    token = jwt.encode(payload, PRIVATE_KEY, algorithm="RS256")
    return token.decode() if isinstance(token, bytes) else token

